const cache = new Map<string, boolean[][]>();

export function sprite(name: string): boolean[][] | null {
  if (!S[name]) return null;
  let c = cache.get(name);
  if (!c) {
    c = S[name].map((r) => r.padEnd(16, '.').slice(0, 16).split('').map((x) => x === '#'));
    cache.set(name, c);
  }
  return c;
}

