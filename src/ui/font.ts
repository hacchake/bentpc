const cache = new Map<string, boolean[][]>();

export function glyph(ch: string): boolean[][] {
  const c = cache.get(ch);
  if (c) return c;
  const src = G[ch] ?? G[ch.toUpperCase()] ?? G['?'];
  const rows = src.split(' ').map((r) => r.split('').map((x) => x === '#'));
  cache.set(ch, rows);
  return rows;
}

